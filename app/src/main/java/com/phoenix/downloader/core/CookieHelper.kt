package com.phoenix.downloader.core

import android.content.Context
import android.webkit.CookieManager
import java.io.File

/**
 * Extracts WebView cookies and saves in Netscape format for yt-dlp.
 * Helps bypass YouTube bot detection by using real browser cookies.
 */
object CookieHelper {
    
    private const val COOKIE_FILE = "cookies.txt"
    
    /**
     * Extract cookies for a URL from WebView's CookieManager and save to file.
     * Returns the file path, or null if no cookies.
     */
    fun saveCookiesForUrl(context: Context, url: String): String? {
        return try {
            val cookieManager = CookieManager.getInstance()
            val cookies = cookieManager.getCookie(url) ?: return null
            
            if (cookies.isEmpty()) return null
            
            val file = File(context.filesDir, COOKIE_FILE)
            file.bufferedWriter().use { writer ->
                writer.write("# Netscape HTTP Cookie File\n")
                writer.write("# Generated by Phoenix Downloader\n\n")
                
                // Parse "name=value; name2=value2" format
                cookies.split(";").forEach { cookie ->
                    val parts = cookie.trim().split("=", limit = 2)
                    if (parts.size == 2) {
                        val name = parts[0].trim()
                        val value = parts[1].trim()
                        // Extract domain from URL
                        val domain = try {
                            val host = android.net.Uri.parse(url).host ?: ""
                            if (host.startsWith("www.")) host.substring(4) else host
                        } catch (e: Exception) { "" }
                        
                        if (domain.isNotEmpty() && name.isNotEmpty()) {
                            val dotDomain = if (domain.startsWith(".")) domain else ".$domain"
                            // Format: domain, TRUE, /, FALSE, 0, name, value
                            writer.write("$dotDomain\tTRUE\t/\tFALSE\t0\t$name\t$value\n")
                        }
                    }
                }
            }
            file.absolutePath
        } catch (e: Exception) {
            e.printStackTrace()
            null
        }
    }
    
    /**
     * Get the cookie file path if it exists.
     */
    fun getCookieFilePath(context: Context): String? {
        val file = File(context.filesDir, COOKIE_FILE)
        return if (file.exists() && file.length() > 0) file.absolutePath else null
    }
}
